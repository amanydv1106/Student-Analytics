from fastapi import APIRouter, Depends, HTTPException, status
from typing import List, Dict, Any
from backend.app.schemas.student_report import StudentReportInput, StudentPerformanceReport, ReportHistoryItem
from backend.app.services.student_portal import student_portal_service
from backend.app.api.routes_auth import get_current_user

router = APIRouter(prefix="/api/student", tags=["Student Diagnostic Reports"])

@router.post("/report", response_model=StudentPerformanceReport)
def generate_personal_report(
    report_input: StudentReportInput,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    """Generate comprehensive student diagnostic report based on submitted academic marks and indicators."""
    return student_portal_service.generate_student_report(
        user=current_user,
        report_input=report_input
    )

@router.get("/report/{report_id}", response_model=StudentPerformanceReport)
def get_specific_report(
    report_id: int,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    """Fetch complete details of a specific historical report."""
    rep = student_portal_service.get_student_report_by_id(current_user["id"], report_id, current_user)
    if not rep:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Report not found")
    return rep

@router.get("/history", response_model=List[ReportHistoryItem])
def get_personal_report_history(
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    """Fetch past diagnostic reports generated by the authenticated student."""
    return student_portal_service.get_student_history(current_user["id"])

@router.delete("/report/{report_id}")
def delete_single_report(
    report_id: int,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    """Delete a single report from student history."""
    success = student_portal_service.delete_student_report(current_user["id"], report_id)
    if not success:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Report not found")
    return {"message": "Report deleted successfully"}

@router.delete("/history")
def clear_all_history(
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    """Clear all reports for the authenticated student."""
    count = student_portal_service.clear_student_history(current_user["id"])
    return {"message": f"Cleared {count} reports from history"}

